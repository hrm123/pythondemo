def MoveZerosToTheEnd(arr):
    zeroIndex = None
    #print(f"source array: {arr}")
    for iter in range(len(arr)):
        if zeroIndex is None:
            if arr[iter] == 0:
                zeroIndex = iter
            else:
                continue # move to next iteration
        if arr[iter] !=0:
            arr[zeroIndex], arr[iter] = arr[iter], arr[zeroIndex]
            zeroIndex += 1 # the non-zero one will be always the first one after current zero or all the next zeros
    #print(f"response  array: {arr}")
    return arr

