# nth largest element in an array using quickselect algorithm - take random (middle) element from array & move it to its correct place in the array.
# Find its  correct place /'pivotindex' such that all elements to
# its left are greater than pivot and all elements to its right are less than pivot. 
# Check if the correctplace / pivotIndex == n-1 , if yes, we have found nth largest element. Else, the nth largest e;ement could lie on left or right side of the 
# array. Select the appropriate sidef and then  repeat the process. this goes on till   we find the nth largest element
# It is O(n) because we are looking at each element of the array only once (actually ~twice - N + N/2+N/4 ... = 2N). Each iteration reduces the number of elements to be looked at by ~half and we only look at one side and discard the other side..
def NthLargestElement(arr, n):
    # O(n) time complexity, O(1) space complexity (since it is inplace implementation) - using quickselect algorithm. Note quickselect works only on one side of pivot, while quicksort works on bth side of array since it has to sort entire array.of the array 
    assert(len(arr) >= n and n > 0), "Array must have at least n elements and n must be positive"
    # print(f"input array={arr}, nth ={n}")
    # if number of distinct elements are less than n, then return None
    if(len(set(arr)) < n): # python array/list to set is O(n) time complexity.. hence this function doe snto change the complexity of algorithm
        return None

    def partition(left, right, pivotIndex):
        
        pivotValue = arr[pivotIndex]
        # print("---------partition start-----------")
        # print(f"partition({left}, {right}, pivotIndex={pivotIndex},pivotValue={pivotValue}) ")
        # move pivot to end
        arr[pivotIndex], arr[right] = arr[right], arr[pivotIndex]
        storeIndex = left
        for i in range(left, right):
            if arr[i] > pivotValue: # note: '>' for nth largest
                arr[storeIndex], arr[i] = arr[i], arr[storeIndex] # swap to the left boundary that as all elements less value than  pivot element
                storeIndex += 1
        # move pivot to its final place
        arr[right], arr[storeIndex] = arr[storeIndex], arr[right] # now all elelements less than pivot value are towards its left and all elements greater than pivot value are towards its right
        # print(f"arr={arr}, newPivotIndex={storeIndex}")
        
        # print("---------partition  end-----------")
        return storeIndex  # index of the pivot such that all elements to its left are lesser than pivot value and all elements to its right are greater than pivot value

    left, right = 0, len(arr) - 1 #left is first element and right is last element
    pivotIndex = left + (right - left) // 2 # choosing middle element as pivot

    while pivotIndex>0 and pivotIndex<len(arr): # partition work looks at reducing number of array elements each iteration - is = N + N/2 + N/4 + ... = 2N = O(N)
        pivotIndex = left + (right - left) // 2 # choosing middle element as pivot
        pivotNewIndex = partition(left, right, pivotIndex) # the middle element has been placed at new index such that all elenments to its left are lesser and all elements to its right are greater
        if pivotNewIndex == -1:
            return None
        if pivotNewIndex == n - 1: # if new pivot is nth position then we have the answer
            # print("final array:", arr)
            # print("nth largest element index in final array:", pivotNewIndex)

            return arr[pivotNewIndex]
        elif pivotNewIndex < n - 1: # if new pivot index is less than nth position, we need to search in right half
            if pivotNewIndex + 1 > right:
                return None
            left = pivotNewIndex + 1
        else:
            if pivotNewIndex - 1 < left:
                return None
            right = pivotNewIndex - 1 # if new pivot index is greater than nth position, we need to search in left half
    return None


