def IsArraySorted(arr): # O(n) time complexity, O(1) space complexity - determines if array is either sorted ascending or sorted descending
    assert(len(arr) > 0), "Array must have at least one element"
    arrIsAscending = False
    arrIsDescending = False
    orderSet = False
    for i in range(1,len(arr)):
        if not orderSet:
            if arr[i] < arr[i-1] and orderSet == False:
                arrIsAscending = True
                orderSet = True
            if arr[i] > arr[i-1] and orderSet == False:
                arrIsDescending = True
                orderSet = True
        if orderSet == True:
            if arr[i] > arr[i-1] and arrIsAscending == True: # first adjacent non-equal element resulted in descending order. Current adjacent elements are in ascending order.
                return False
            if arr[i] < arr[i-1] and arrIsDescending == True: # first adjacent non-equal element resulted in descending order. Current adjacent elements are in ascending order.
                return False
    return True

