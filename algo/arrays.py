'''
leader in an array (sorted or unsorted) is a number which does not have anything greater than it on right of the array.
Ex - for array [7,10,4,3,6,5,2] the answer is 10,6,5,2
Ruick solution I could think of  -  traverse from end of array noting the greatest number hit so far ('greatest_so_far'). 
If current number is greater than the greatest_so_far then it belongs to the answer. and greatest_so_far becomes current number
'''
def PrintLeadersInAnArray(arr): 
    n = len(arr)
    greatest_so_far = arr[n-1]
    response = []
    response.append(greatest_so_far)
    for y in reversed(range(n-1)):
        if arr[y]>=greatest_so_far:
            response.append(arr[y])
            greatest_so_far = arr[y]
    response.reverse()
    # print(f"response  array: {response}")
    return response

