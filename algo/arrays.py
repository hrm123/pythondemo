def ReverseArrayInPlace(arr): # O(n) time complexity, O(1) space complexity - reverses the array in place
    n = len(arr)
    for iter in range(n//2):
        # print(f"swapping arr[{iter}]={arr[iter]} and arr[{n - iter -1}]={arr[n - iter -1]}")
        arr[iter], arr[n-iter-1] = arr[n-iter-1], arr[iter]
    return arr

