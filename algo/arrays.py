def SecondLargestElement(arr): # O(n) time complexity, O(1) space complexity
    assert(len(arr) >= 2), "Array must have at least two elements"
    largest = arr[0]
    secondLargest = None
    for item in arr:
        if largest is None or item > largest:
            secondLargest = largest
            largest = item
        elif (secondLargest is None or item > secondLargest) and item != largest:
            secondLargest = item
    return secondLargest

