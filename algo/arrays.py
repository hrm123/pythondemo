def CounterClockWiseRotate(arr): # O(n) time complexity, O(1) space complexity - rotates the array counter clockwise by one position
    # print(f"source array: {arr}")
    assert(len(arr) > 0), "Array must have at least one element"
    n = len(arr)
    temp = arr[0]
    for iter in range(1, n):
        # print(f"sending arr[{iter}]={arr[iter]} to arr[{iter-1}]={arr[iter-1]}")
        arr[iter-1] = arr[iter]
    arr[n-1]= temp
    # print(f"response  array: {arr}")
    return arr

